/**
 * Custom Docusaurus plugin: docs-sidebar-global-data
 *
 * The docs sidebar tree is normally code-split with the docs routes, so it is
 * not available on non-doc pages (e.g. the homepage). This plugin resolves the
 * same tree from `sidebars.js` + each doc's frontmatter at build time and
 * exposes it via global data, so the homepage can render the *real*
 * `@theme/DocSidebar` with identical labels, links and structure.
 *
 * It derives everything from existing files (no manual upkeep): add a doc to
 * `sidebars.js` and it shows up here automatically.
 *
 * Assumes the simple sidebar style this site uses: string doc ids and
 * categories only (no autogenerated/ref/link items, no custom `slug:`).
 */
const fs = require('fs');
const path = require('path');

const ROUTE_BASE_PATH = '/docs';

function readFile(file) {
  let raw = fs.readFileSync(file, 'utf8');
  // These docs are saved with a UTF-8 BOM; strip it so the frontmatter
  // delimiter sits at the very start of the string.
  if (raw.charCodeAt(0) === 0xfeff) {
    raw = raw.slice(1);
  }
  return raw;
}

function readFrontmatterLabel(docsDir, id) {
  const candidates = [
    path.join(docsDir, `${id}.md`),
    path.join(docsDir, `${id}.mdx`),
  ];
  const file = candidates.find((p) => fs.existsSync(p));
  if (!file) {
    return null;
  }
  const raw = readFile(file);
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) {
    return null;
  }
  const fm = match[1];
  const get = (key) => {
    const m = fm.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
    if (!m) return null;
    return m[1].trim().replace(/^['"]|['"]$/g, '');
  };
  return get('sidebar_label') || get('title') || null;
}

function titleFromId(id) {
  return id
    .split('/')
    .pop()
    .replace(/-/g, ' ')
    .replace(/\b\w/g, (l) => l.toUpperCase());
}

function resolveItem(item, docsDir) {
  // Category: { type: 'category', label, items: [...] }
  if (item && item.type === 'category') {
    return {
      type: 'category',
      label: item.label,
      items: item.items
        .map((sub) => resolveItem(sub, docsDir))
        .filter(Boolean),
      collapsed: item.collapsed !== false,
      collapsible: item.collapsible !== false,
    };
  }
  // Plain doc id (string)
  if (typeof item === 'string') {
    const id = item;
    return {
      type: 'link',
      label: readFrontmatterLabel(docsDir, id) || titleFromId(id),
      href: `${ROUTE_BASE_PATH}/${id}`,
      docId: id,
      unlisted: false,
    };
  }
  // Anything else (object doc/link/ref) — skip; this site doesn't use them.
  return null;
}

module.exports = function docsSidebarGlobalData(context) {
  return {
    name: 'docs-sidebar-global-data',
    async loadContent() {
      const sidebars = require(path.join(context.siteDir, 'sidebars.js'));
      const docsDir = path.join(context.siteDir, 'docs');
      const items = (sidebars.docs || [])
        .map((item) => resolveItem(item, docsDir))
        .filter(Boolean);
      return {sidebar: items};
    },
    async contentLoaded({content, actions}) {
      actions.setGlobalData(content);
    },
  };
};
